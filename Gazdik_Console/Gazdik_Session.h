#pragma once
#include <queue>
#include <mutex>
#include <windows.h>
#include "Gazdik_Message.h"

// ============================================================
// Gazdik_Session.h
//
// Что это такое?
// Session — это "почтовый ящик" для одного рабочего потока.
//
// Представь: у каждого жильца в доме есть свой ящик.
// Кто угодно может бросить туда письмо (pushMessage).
// Жилец вынимает письмо, когда оно появилось (pullMessage).
// Если ящик пуст — жилец просто ждёт у ящика.
//
// Внутри:
//   queue<Message> — очередь писем (FIFO: первым пришло — первым ушло)
//   mutex          — замок, чтобы двое не лезли в ящик одновременно
//   HANDLE event   — "звонок" — будит поток, когда письмо пришло
// ============================================================

class Gazdik_Session {
private:
    std::queue<Gazdik_Message> queue;  // очередь сообщений
    std::mutex mtx;                    // мьютекс для защиты очереди
    HANDLE eventHandle;                // Win32 Event — "звонок у ящика"

public:
    int sessionId;  // уникальный номер этого ящика (= id потока)

    // Конструктор — создаём ящик для потока с данным id
    Gazdik_Session(int id);

    // Деструктор — закрываем Win32 Event handle (освобождаем ресурс ОС)
    ~Gazdik_Session();

    // Положить сообщение в ящик (может вызвать ЛЮБОЙ поток)
    void pushMessage(const Gazdik_Message& msg);

    // Вынуть сообщение из ящика (вызывает только ВЛАДЕЛЕЦ потока)
    // Блокирует вызывающий поток, пока ящик пуст
    // Возвращает true если сообщение получено, false если ящик пуст
    bool pullMessage(Gazdik_Message& msg);
};
