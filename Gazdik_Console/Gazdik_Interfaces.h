#pragma once

// ============================================================
// Gazdik_Interfaces.h
//
// Что это такое?
// Это файл с "контрактами" — правилами, которым должны следовать
// другие классы. В C++ такие контракты называются абстрактными
// классами (интерфейсами).
//
// Зачем это нужно?
// Представь, что ты хочешь отправить посылку. Тебе неважно,
// везёт её машина, поезд или самолёт — ты просто знаешь,
// что посылка доедет. Вот ISender и IReceiver — это
// "соглашение о доставке". Кто угодно может реализовать
// эти интерфейсы, и Message будет работать с ними.
// ============================================================

// Предварительное объявление — говорим компилятору:
// "Такая структура существует, подробности — позже"
struct Gazdik_Message;

// Интерфейс "Отправитель"
// Любой класс, который умеет отправлять сообщения,
// должен реализовать метод send()
class Gazdik_ISender {
public:
    // pure virtual (= 0) означает: "этот класс сам по себе
    // ничего не делает — его ОБЯЗАН реализовать потомок"
    virtual void send(Gazdik_Message& msg) const = 0;

    // Виртуальный деструктор — важен при удалении через указатель на базовый класс
    virtual ~Gazdik_ISender() = default;
};

// Интерфейс "Получатель"
// Любой класс, который умеет получать сообщения,
// должен реализовать метод receive()
class Gazdik_IReceiver {
public:
    virtual void receive(Gazdik_Message& msg) const = 0;
    virtual ~Gazdik_IReceiver() = default;
};
