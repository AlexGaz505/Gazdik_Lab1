// ============================================================
// Program.cs — точка входа C# приложения
//
// Это самый первый файл, который запускается.
// Здесь всего одна задача: создать форму и показать её.
//
// [STAThread] — обязательная пометка для WinForms приложений.
// STA = Single Threaded Apartment — особый режим работы COM
// объектов, которые используются под капотом в Windows.
// Без этой пометки окно может вести себя некорректно.
// ============================================================

namespace Gazdik_Dialog
{
    internal static class Program
    {
        [STAThread]
        static void Main()
        {
            // Инициализирует настройки приложения (DPI, шрифты и т.д.)
            ApplicationConfiguration.Initialize();

            // Запускаем форму Form1 и отдаём управление Windows
            // Application.Run не вернётся пока форма не закроется
            Application.Run(new Form1());
        }
    }
}
